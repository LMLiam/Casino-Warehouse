#!/usr/bin/env node

export const defaultAutofixOptions = {
  allowRules: [],
  branchPrefix: 'security/autofix',
  labels: ['type:maintenance', 'area:tooling', 'security'],
  maxAlerts: 3,
  minSeverity: 'high',
  pollAttempts: 18,
  pollSeconds: 10,
};

const millisecondsPerSecond = 1000;

const severityOrder = new Map([
  ['note', 0],
  ['warning', 1],
  ['low', 2],
  ['medium', 3],
  ['error', 3],
  ['high', 4],
  ['critical', 5],
]);

export function normalizeOptions(options = {}) {
  return {
    ...defaultAutofixOptions,
    ...options,
    allowRules: normalizeList(options.allowRules ?? defaultAutofixOptions.allowRules),
    labels: normalizeList(options.labels ?? defaultAutofixOptions.labels),
    maxAlerts: parseIntegerOption('max-alerts', options.maxAlerts ?? defaultAutofixOptions.maxAlerts, { min: 0 }),
    pollAttempts: parseIntegerOption('poll-attempts', options.pollAttempts ?? defaultAutofixOptions.pollAttempts, { min: 1 }),
    pollSeconds: parseIntegerOption('poll-seconds', options.pollSeconds ?? defaultAutofixOptions.pollSeconds, { min: 1 }),
  };
}

export function severityValue(severity) {
  return severityOrder.get(String(severity ?? '').toLowerCase()) ?? -1;
}

export function alertSeverity(alert) {
  return alert?.rule?.security_severity_level ?? alert?.rule?.severity ?? 'unknown';
}

export function alertRuleId(alert) {
  return String(alert?.rule?.id ?? 'unknown-rule');
}

export function alertRuleName(alert) {
  return String(alert?.rule?.description ?? alert?.rule?.name ?? alertRuleId(alert));
}

export function alertHtmlUrl(alert) {
  return String(alert?.html_url ?? alert?.url ?? '');
}

export function affectedFiles(alert, instances = []) {
  const paths = new Set();
  const primaryPath = alert?.most_recent_instance?.location?.path;
  if (primaryPath) {
    paths.add(primaryPath);
  }
  for (const instance of instances) {
    const path = instance?.location?.path;
    if (path) {
      paths.add(path);
    }
  }
  return [...paths].sort();
}

export function isDefaultBranchAlert(alert, defaultBranch) {
  const expectedRef = `refs/heads/${defaultBranch}`;
  return alert?.most_recent_instance?.ref === expectedRef;
}

export function buildAutofixBranchName(alert, options = {}) {
  const normalized = normalizeOptions(options);
  const rule = alertRuleId(alert)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40);
  return `${normalized.branchPrefix}/alert-${alert.number}-${rule || 'rule'}`;
}

export function buildPullRequestTitle(alert) {
  const summary = alertRuleName(alert)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .slice(0, 60);
  return `security(codeql): autofix ${summary || alertRuleId(alert)}`;
}

export function buildPullRequestBody(alert, details = {}) {
  const files = details.files?.length ? details.files : affectedFiles(alert, details.instances);
  const fileList = files.length > 0 ? files.map((file) => `- \`${file}\``).join('\n') : '- Not reported by the alert payload';
  const fixSummary = details.autofixDescription?.trim() || 'Generated by GitHub Copilot Autofix. Review the committed diff before marking this draft ready.';

  return `## Summary

Create a draft Copilot Autofix pull request for CodeQL alert ${alert.number}.

- Alert: ${alertHtmlUrl(alert) || `#${alert.number}`}
- Rule: \`${alertRuleId(alert)}\` (${alertRuleName(alert)})
- Severity: ${alertSeverity(alert)}
- Generated fix summary: ${fixSummary}

Affected files:

${fileList}

## Type

- [x] Bug fix
- [ ] Feature
- [ ] Documentation
- [ ] Refactor
- [x] Test or tooling

## Checks

- [x] I read \`CONTRIBUTING.md\`.
- [x] I kept generated build output out of this pull request.
- [x] I added or updated tests, or explained why tests are not needed.
- [x] I ran the relevant local checks.

## Testing

Commands run:

\`\`\`text
Not run - draft Copilot Autofix PR generated for maintainer validation.
\`\`\`

## Notes

This pull request was opened as a draft by the CodeQL Autofix automation. A maintainer should inspect the generated diff, run the relevant checks, and only then mark it ready for review.`;
}

export function findExistingFixPullRequest(alert, pullRequests = [], options = {}) {
  const branchName = buildAutofixBranchName(alert, options);
  const alertUrl = alertHtmlUrl(alert);
  const alertUrlFragment = alertUrl ? alertUrl.toLowerCase() : '';
  const alertNumberFragment = `/code-scanning/${alert.number}`;

  return pullRequests.find((pullRequest) => {
    const head = String(pullRequest.head?.ref ?? pullRequest.headRefName ?? '').toLowerCase();
    const title = String(pullRequest.title ?? '').toLowerCase();
    const body = String(pullRequest.body ?? '').toLowerCase();
    return (
      head === branchName.toLowerCase() ||
      title.includes(`alert ${alert.number}`) ||
      body.includes(alertNumberFragment) ||
      (alertUrlFragment.length > 0 && body.includes(alertUrlFragment))
    );
  });
}

export function planAutofixPullRequests({ alerts, defaultBranch, openPullRequests, options = {} }) {
  const normalized = normalizeOptions(options);
  const candidates = [];
  const skipped = [];

  for (const alert of alerts) {
    const skipReasons = skipReasonsForAlert(alert, defaultBranch, openPullRequests, normalized);
    if (skipReasons.length > 0) {
      skipped.push({ alert, reasons: skipReasons });
      continue;
    }

    if (candidates.length >= normalized.maxAlerts) {
      skipped.push({ alert, reasons: ['max-alerts-reached'] });
      continue;
    }

    candidates.push({
      alert,
      branchName: buildAutofixBranchName(alert, normalized),
      labels: normalized.labels,
      title: buildPullRequestTitle(alert),
    });
  }

  return { candidates, skipped };
}

export function skipReasonsForAlert(alert, defaultBranch, openPullRequests, options = {}) {
  const normalized = normalizeOptions(options);
  const reasons = [];
  const allowRules = new Set(normalized.allowRules);

  if (alert?.state !== 'open') {
    reasons.push('not-open');
  }
  if (!isDefaultBranchAlert(alert, defaultBranch)) {
    reasons.push('not-default-branch');
  }
  if (severityValue(alertSeverity(alert)) < severityValue(normalized.minSeverity)) {
    reasons.push('below-min-severity');
  }
  if (allowRules.size > 0 && !allowRules.has(alertRuleId(alert))) {
    reasons.push('rule-not-allowed');
  }
  if (findExistingFixPullRequest(alert, openPullRequests, normalized)) {
    reasons.push('existing-open-fix-pr');
  }

  return reasons;
}

export function createGitHubClient({ token, apiUrl = 'https://api.github.com', fetchImpl = fetch }) {
  const headers = {
    Accept: 'application/vnd.github+json',
    Authorization: `Bearer ${token}`,
    'Content-Type': 'application/json',
    'X-GitHub-Api-Version': '2026-03-10',
  };

  const request = async (method, path, body) => {
    const response = await fetchImpl(`${apiUrl}${path}`, {
      body: body === undefined ? undefined : JSON.stringify(body),
      headers,
      method,
    });
    const text = await response.text();
    const data = text ? JSON.parse(text) : undefined;

    if (!response.ok) {
      const message = data?.message ? `: ${data.message}` : '';
      throw new Error(`${method} ${path} failed with ${response.status}${message}`);
    }

    return { data, headers: response.headers, status: response.status };
  };

  const paginate = async (path) => {
    const results = [];
    let nextPath = path;
    while (nextPath) {
      const { data, headers: responseHeaders } = await request('GET', nextPath);
      results.push(...data);
      nextPath = nextPathFromLink(responseHeaders.get('link'), apiUrl);
    }
    return results;
  };

  return { paginate, request };
}

export async function runAutofixAutomation({ client, defaultBranch, owner, repo, mode, options }) {
  const normalized = normalizeOptions(options);
  const encodedRef = encodeURIComponent(`refs/heads/${defaultBranch}`);
  const alerts = await client.paginate(`/repos/${owner}/${repo}/code-scanning/alerts?state=open&ref=${encodedRef}&tool_name=CodeQL&per_page=100`);
  const openPullRequests = await client.paginate(`/repos/${owner}/${repo}/pulls?state=open&per_page=100`);
  const plan = planAutofixPullRequests({ alerts, defaultBranch, openPullRequests, options: normalized });

  logPlan(plan, defaultBranch, normalized);

  if (mode === 'dry-run') {
    return { ...plan, created: [], failed: [] };
  }

  const created = [];
  const failed = [];
  for (const candidate of plan.candidates) {
    try {
      created.push(await createDraftAutofixPullRequest({ candidate, client, defaultBranch, owner, repo, options: normalized }));
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      failed.push({ alert: candidate.alert.number, branchName: candidate.branchName, error: message });
      console.error(`Skipped alert ${candidate.alert.number}: ${message}`);
    }
  }

  return { ...plan, created, failed };
}

export async function createDraftAutofixPullRequest({ candidate, client, defaultBranch, owner, repo, options }) {
  const normalized = normalizeOptions(options);
  const autofix = await requestAutofix({ alertNumber: candidate.alert.number, client, owner, repo, options: normalized });
  const branchRef = `refs/heads/${candidate.branchName}`;
  const defaultRef = await client.request('GET', `/repos/${owner}/${repo}/git/ref/heads/${encodeURIComponent(defaultBranch)}`);
  const sha = defaultRef.data?.object?.sha;
  if (!sha) {
    throw new Error(`Could not resolve ${defaultBranch} branch SHA.`);
  }

  let pullRequestCreated = false;

  await client.request('POST', `/repos/${owner}/${repo}/git/refs`, { ref: branchRef, sha });

  try {
    await client.request('POST', `/repos/${owner}/${repo}/code-scanning/alerts/${candidate.alert.number}/autofix/commits`, {
      message: `security(codeql): apply autofix for alert ${candidate.alert.number}`,
      target_ref: branchRef,
    });

    const instances = await client.paginate(`/repos/${owner}/${repo}/code-scanning/alerts/${candidate.alert.number}/instances?per_page=100`);
    const body = buildPullRequestBody(candidate.alert, {
      autofixDescription: autofix.description,
      instances,
    });
    const pullRequest = await client.request('POST', `/repos/${owner}/${repo}/pulls`, {
      base: defaultBranch,
      body,
      draft: true,
      head: candidate.branchName,
      maintainer_can_modify: true,
      title: candidate.title,
    });
    pullRequestCreated = true;

    if (candidate.labels.length > 0) {
      await client.request('POST', `/repos/${owner}/${repo}/issues/${pullRequest.data.number}/labels`, { labels: candidate.labels });
    }

    return { alert: candidate.alert.number, pullRequest: pullRequest.data.html_url };
  } catch (error) {
    if (!pullRequestCreated) {
      await deleteBranchRef({ branchName: candidate.branchName, client, owner, repo });
    }

    throw error;
  }
}

export async function requestAutofix({ alertNumber, client, owner, repo, options, delayImpl = delay }) {
  const normalized = normalizeOptions(options);
  const created = await client.request('POST', `/repos/${owner}/${repo}/code-scanning/alerts/${alertNumber}/autofix`);
  if (created.data?.status === 'success') {
    return created.data;
  }

  for (let attempt = 0; attempt < normalized.pollAttempts; attempt += 1) {
    await delayImpl(normalized.pollSeconds * millisecondsPerSecond);
    const status = await client.request('GET', `/repos/${owner}/${repo}/code-scanning/alerts/${alertNumber}/autofix`);
    if (status.data?.status === 'success') {
      return status.data;
    }
    if (['error', 'failed', 'dismissed'].includes(status.data?.status)) {
      throw new Error(`Autofix for alert ${alertNumber} ended with status ${status.data.status}.`);
    }
  }

  throw new Error(`Autofix for alert ${alertNumber} did not finish within the polling limit.`);
}

export function parseCliArguments(argv) {
  const args = new Map();
  for (const item of argv) {
    const [key, ...valueParts] = item.replace(/^--/, '').split('=');
    args.set(key, valueParts.join('=') || 'true');
  }
  return args;
}

export function optionsFromEnvironment(env = process.env, argv = process.argv.slice(2)) {
  const args = parseCliArguments(argv);
  const mode = args.get('mode') ?? env.AUTOFIX_MODE ?? 'dry-run';
  const repository = args.get('repo') ?? env.GITHUB_REPOSITORY;
  if (!repository || !repository.includes('/')) {
    throw new Error('Set GITHUB_REPOSITORY or pass --repo=OWNER/REPO.');
  }

  const [owner, repo] = repository.split('/');
  return {
    apiUrl: env.GITHUB_API_URL ?? 'https://api.github.com',
    defaultBranch: args.get('default-branch') ?? env.DEFAULT_BRANCH ?? 'main',
    mode: mode === 'create-draft-prs' ? 'create' : 'dry-run',
    options: normalizeOptions({
      allowRules: args.get('allow-rules') ?? env.AUTOFIX_ALLOW_RULES,
      labels: args.get('labels') ?? env.AUTOFIX_LABELS,
      maxAlerts: args.get('max-alerts') ?? env.AUTOFIX_MAX_ALERTS,
      minSeverity: args.get('min-severity') ?? env.AUTOFIX_MIN_SEVERITY,
      pollAttempts: args.get('poll-attempts') ?? env.AUTOFIX_POLL_ATTEMPTS,
      pollSeconds: args.get('poll-seconds') ?? env.AUTOFIX_POLL_SECONDS,
    }),
    owner,
    repo,
    token: env.GITHUB_TOKEN,
  };
}

function normalizeList(value) {
  if (Array.isArray(value)) {
    return value.filter(Boolean);
  }
  return String(value ?? '')
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean);
}

function parseIntegerOption(name, value, { min }) {
  const normalized = typeof value === 'string' ? value.trim() : value;
  const integerString = typeof normalized === 'string' && /^-?\d+$/.test(normalized);
  const parsed = typeof normalized === 'number' || integerString ? Number(normalized) : Number.NaN;
  if (!Number.isFinite(parsed) || !Number.isInteger(parsed) || parsed < min) {
    throw new Error(`${name} must be an integer greater than or equal to ${min}. Received ${formatOptionValue(value)}.`);
  }

  return parsed;
}

function formatOptionValue(value) {
  return typeof value === 'string' ? JSON.stringify(value) : String(value);
}

function nextPathFromLink(linkHeader, apiUrl) {
  if (!linkHeader) {
    return undefined;
  }
  const nextLink = linkHeader.split(',').find((part) => part.includes('rel="next"'));
  const match = nextLink?.match(/<([^>]+)>/);
  if (!match) {
    return undefined;
  }

  try {
    const base = new URL(apiUrl);
    const url = new URL(match[1], base);
    if (url.origin !== base.origin) {
      return undefined;
    }

    const basePath = base.pathname.replace(/\/+$/, '');
    let nextPath = url.pathname;
    if (basePath) {
      if (url.pathname !== basePath && !url.pathname.startsWith(`${basePath}/`)) {
        return undefined;
      }
      nextPath = url.pathname.slice(basePath.length) || '/';
    }

    return `${nextPath}${url.search}`;
  } catch {
    return undefined;
  }
}

async function deleteBranchRef({ branchName, client, owner, repo }) {
  try {
    await client.request('DELETE', `/repos/${owner}/${repo}/git/refs/${encodeURIComponent(`heads/${branchName}`)}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`Could not clean up ${branchName}: ${message}`);
  }
}

function logPlan(plan, defaultBranch, options) {
  console.log(`CodeQL Autofix plan for ${defaultBranch}`);
  console.log(`Mode: dry-run by default; max alerts: ${options.maxAlerts}; min severity: ${options.minSeverity}`);
  console.log(`Candidates: ${plan.candidates.length}`);
  for (const candidate of plan.candidates) {
    console.log(`- Alert ${candidate.alert.number}: ${alertRuleId(candidate.alert)} -> ${candidate.branchName}`);
  }
  console.log(`Skipped: ${plan.skipped.length}`);
  for (const skipped of plan.skipped) {
    console.log(`- Alert ${skipped.alert.number}: ${skipped.reasons.join(', ')}`);
  }
  appendStepSummary(plan, defaultBranch, options);
}

function appendStepSummary(plan, defaultBranch, options) {
  if (!process.env.GITHUB_STEP_SUMMARY) {
    return;
  }
  const lines = [
    `## CodeQL Autofix ${options.maxAlerts === 0 ? 'Disabled' : 'Plan'}`,
    '',
    `Default branch: \`${defaultBranch}\``,
    `Minimum severity: \`${options.minSeverity}\``,
    `Maximum draft PRs per run: \`${options.maxAlerts}\``,
    '',
    `Candidates: ${plan.candidates.length}`,
    ...plan.candidates.map((candidate) => `- Alert ${candidate.alert.number}: \`${alertRuleId(candidate.alert)}\` -> \`${candidate.branchName}\``),
    '',
    `Skipped: ${plan.skipped.length}`,
    ...plan.skipped.map((skipped) => `- Alert ${skipped.alert.number}: ${skipped.reasons.join(', ')}`),
    '',
  ];
  import('node:fs').then((fs) => fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${lines.join('\n')}\n`));
}

function delay(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function main() {
  const config = optionsFromEnvironment();
  if (!config.token) {
    throw new Error('GITHUB_TOKEN is required.');
  }
  const client = createGitHubClient({ apiUrl: config.apiUrl, token: config.token });
  await runAutofixAutomation(client ? { ...config, client } : undefined);
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
